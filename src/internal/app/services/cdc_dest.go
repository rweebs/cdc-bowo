type CDCDestServices struct {
	dbSource           lib.Database
	dbDest             lib.Database
	rdb                lib.Cache
	primaryKeyList     map[string][]string
	redisStreamList    map[string]string
	timeStampCutOff    int64
	transformationList map[string]config.DDLTransform
	config             config.Config
}

func (s *CDCDestServices) StartService(startTimestamp int64) {
	// Loop:
	failedStatement := types.NewFIFOMap()
	for {

		entries, err := s.rdb.Cache.XRead(context.Background(), &redis.XReadArgs{

			Streams: makeStream(s.redisStreamList),
			Count:   1000,
			Block:   0,
		}).Result()
		if err != nil {
			log.Println(err)
			// continue
		}

		for _, streamEntries := range entries {
			for _, entry := range streamEntries.Messages {

				log.Println("Received event from stream", streamEntries.Stream)
				for _, v := range entry.Values {
					var sql string
					var dat model.AutoGenerated
					if err := json.Unmarshal([]byte(fmt.Sprintf("%v", v)), &dat); err != nil {
						log.Println(err)
					}
					// data, _ := json.MarshalIndent(dat, "", "  ")
					// // Print json formatted
					// log.Println(string(data))
					if dat.Payload.TsMs < startTimestamp {
						continue
					}

					if val, ok := s.transformationList[fmt.Sprintf("%s.%s", dat.Payload.Source.Schema, dat.Payload.Source.Table)]; ok {
						dat = utils.ConvertSchemaDest(dat, val)

						sql = utils.ConvertDataToSQL(dat, s.primaryKeyList, val, false, s.dbSource.Db)
					} else {
						sql = utils.ConvertDataToSQL(dat, s.primaryKeyList, config.DDLTransform{}, false, s.dbSource.Db)
					}
					_, err := utils.SQLExecutor(s.dbSource.Db, sql)
					if err != nil {
						// log.Println(err)
						if err.(*pq.Error).Code == "23503" {
							failedStatement.Set(entry.ID, sql)
						}
					}
					failedStatementKeys := failedStatement.Keys()
					for _, key := range failedStatementKeys {
						if sql, ok := failedStatement.Get(key); ok {
							_, err := utils.SQLExecutor(s.dbDest.Db, sql.(string))
							if err != nil {
								log.Println(err)
							} else {
								failedStatement.Delete(key)
							}
						}
					}
					// log.Println(utils.ConvertDataToSQL(dat, s.primaryKeyList, config.DDLTransform{}))
				}
				s.redisStreamList[streamEntries.Stream] = entry.ID
			}
		}
	}
}

