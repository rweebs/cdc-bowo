func (s *CDCDestServices) StopService() {
	data, _ := json.Marshal(s.redisStreamList)
	s.rdb.Cache.Set(context.Background(), "destRedisStreamList", data, 0)
	log.Println("Stop Dest Service")

}
func NewCDCDestServices(dbSource lib.Database, dbDest lib.Database, rdb lib.Cache, config config.Config) *CDCDestServices {
	sqlFile, err := ioutil.ReadFile(config.SQLFile)
	if err != nil {
		log.Panic(`Error reading SQL file`)
	}
	return &CDCDestServices{
		dbSource:           dbSource,
		dbDest:             dbDest,
		rdb:                rdb,
		primaryKeyList:     initPrimaryKeyList(dbSource.Db),
		redisStreamList:    initRedisStreamList(dbSource.Db, rdb.Cache, "destRedisStreamList", config.DestConfig.DebeziumPublication, config.DestConfig.RedisTopicPrefix),
		timeStampCutOff:    time.Now().UnixNano() / int64(time.Millisecond),
		config:             config,
		transformationList: utils.InitTransformListDestNew(string(sqlFile), config.DDLTransform),
	}
}

