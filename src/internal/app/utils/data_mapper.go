// ConvertTemporalDataTypeDest converts data type from Postgres temporal to Debezium. This is needed to be able to handle dates and times as well as date.
//
// Args:
//
//	data: The data type in auto generated format. This is modified in place.
//	config: The transform configuration that contains information about how to convert the data type
func ConvertTemporalDataTypeDest(data model.AutoGenerated, config config.DDLTransform) model.AutoGenerated {
	dataSchemaFields := data.Schema.Fields[1].Fields
	// Modify data type for the current modify data type.
	for _, v := range config.ModifyDataType {
		// This function will remove any whitespace from the column name.
		for i := range dataSchemaFields {
			// If the column is a column and the column is a debezium postgres temporal map it will be set to the debezium type.
			if dataSchemaFields[i].Field == v.Column {
				newTypeRemoveWhiteSpace := strings.ReplaceAll(v.NewType, " ", "")
				newTypeToLower := strings.ToLower(newTypeRemoveWhiteSpace)
				// Set the type of the data schema
				if debeziumType, ok := DebeziumPostgresTemporalMap()[newTypeToLower]; ok {
					dataSchemaFields[i].Type = debeziumType
				}
			}
		}
	}
	data.Schema.Fields[1].Fields = dataSchemaFields
	return data
}

// ConvertSchema converts schema from auto generated schema to database schema. See model. DDLTransform for details.
//
// Args:
//
//	data: The data to convert. This is expected to be a pointer to a struct so it can be type asserted.
//	config: The configuration for the conversion. This is expected to be a pointer to a struct so it can be type asserted
func ConvertSchema(data model.AutoGenerated, config config.DDLTransform) model.AutoGenerated {
	// Drop table if there is any drop table
	if len(config.DropTable) > 0 {
		data = DropTable(data, config)
		return data
	}
	// Rename table if any.
	if len(config.RenameTable) > 0 {
		data = RenameTable(data, config)
	}
	// Rename the column in the data.
	if len(config.RenameColumn) > 0 {
		data = RenameColumn(data, config)
	}
	// Drop the column if any.
	if len(config.DropColumn) > 0 {
		data = DropColumn(data, config)
	}
	// Add a column to the data.
	if len(config.AddColumn) > 0 {
		data = AddColumn(data, config)
	}
	// if len(config.HorizontalSplitting) > 0 {
	// 	data = HorizontalSplitting(data, config)
	// }
	// data2, _ := json.MarshalIndent(data, "", "  ")
	// log.Println(string(data2))
	return data
}

// ConvertSchemaDest converts schema data from schema format to client format. This function is called after the data has been read from the server and before it is written to the database
//
// Args:
//
//	data: the data read from the server
//	config: the configuration for the schema to be used in
func ConvertSchemaDest(data model.AutoGenerated, config config.DDLTransform) model.AutoGenerated {
	// Create table if needed. If the table is not already created create it.
	if len(config.CreateTable) > 0 {
		// Create table if it s not already used.
		if !config.CreateTable[0].BeingUsed {
			data = CreateTableDest(data, config)
		}
		return data
	}
	// Rename table if the config. RenameTable is set to true
	if len(config.RenameTable) > 0 {
		data = RenameTableDest(data, config)
	}
	// Rename the column if any.
	if len(config.RenameColumn) > 0 {
		data = RenameColumnDest(data, config)
	}
	// Drop the column if any.
	if len(config.DropColumn) > 0 {
		data = DropColumnDest(data, config)
	}
	// Add a column to the data.
	if len(config.AddColumn) > 0 {
		data = AddColumnDest(data, config)
	}
	// if len(config.ModifyDataType) > 0 {
	// 	data = ConvertTemporalDataTypeDest(data, config)
	// }
	return data
}
