// AddColumnDest modifies the data to add columns. This is a copy of tableMap. AddColumn that is used for migration.
//
// Args:
//
//	data: The data to modify. The modified data is returned.
//	config: The configuration for the table that is being migrated
func AddColumnDest(data model.AutoGenerated, config config.DDLTransform) model.AutoGenerated {
	// data. Payload. After is a map string interface interface
	if data.Payload.After != nil {
		tableMapAfter := data.Payload.After.(map[string]interface{})

		// Delete the tableMapAfter tableMapAfter. Column.
		for _, v := range config.AddColumn {
			delete(tableMapAfter, v.Column)
		}
		data.Payload.After = tableMapAfter
	}
	// data. Payload. Before is a map string interface interface
	if data.Payload.Before != nil {
		tableMapBefore := data.Payload.Before.(map[string]interface{})
		// Delete the tableMapBefore and tableMapAfter. Column
		for _, v := range config.AddColumn {
			delete(tableMapBefore, v.Column)
		}
		data.Payload.Before = tableMapBefore
	}
	return data
}

// DropColumn removes column from DDL. Note that after and before are mutually exclusive. In the case of dropping a column we need to make sure there is no reference to the column before and after.
//
// Args:
//
//	data: The data that was auto generated. The processed data is returned for convenience.
//	config: The configuration for the transform that will be used
func DropColumn(data model.AutoGenerated, config config.DDLTransform) model.AutoGenerated {
	// Drop column names from the payload.
	if data.Payload.After != nil {
		tableMap := data.Payload.After.(map[string]interface{})

		// Delete all columns from the tableMap.

		for _, v := range config.DropColumn {
			delete(tableMap, v.Column)
		}
		data.Payload.After = tableMap
	}

	// Drop column names from the payload.
	if data.Payload.Before != nil {
		tableMapBefore := data.Payload.Before.(map[string]interface{})

		// Delete all columns from the tableMapBefore.
		for _, v := range config.DropColumn {
			delete(tableMapBefore, v.Column)
		}
		data.Payload.Before = tableMapBefore
	}
	return data
}

// DropColumnDest drops columns from table. The drop column is used to create a column that doesn t exist in the table.
//
// Args:
//
//	data: The data which was auto generated. The modified data is returned.
//	config: The configuration for the model which contains the DDLTransform
func DropColumnDest(data model.AutoGenerated, config config.DDLTransform) model.AutoGenerated {
	// Set the data. Payload. After field to the data. Payload. After.
	if data.Payload.After != nil {
		tableMap := data.Payload.After.(map[string]interface{})
		// Set the default value of drop column
		for _, v := range config.DropColumn {
			// Set the default value of the column.
			if v.IsNullable {
				tableMap[v.Column] = nil
			} else {
				tableMap[v.Column] = v.Default
			}
		}

		data.Payload.After = tableMap
	}
	// Set the data. Payload. Before to the map of column names to default values.
	if data.Payload.Before != nil {
		tableMapBefore := data.Payload.Before.(map[string]interface{})
		// Set the column to the default value if any of the drop columns is nullable.
		for _, v := range config.DropColumn {
			// Set the column to the default value.
			if v.IsNullable {
				tableMapBefore[v.Column] = nil
			} else {
				tableMapBefore[v.Column] = v.Default
			}
		}
		data.Payload.Before = tableMapBefore
	}
	return data
}

