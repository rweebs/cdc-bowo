// Alter column name in after and before schema. This is to support rename column in DDLTransform. The data. Payload should be modified as needed
//
// Args:
//
//	data: The data being processed.
//	config: The configuration for the transformation which is used to determine how to rename
func RenameColumn(data model.AutoGenerated, config config.DDLTransform) model.AutoGenerated {
	// This method is used to remove the column names from the payload.
	if data.Payload.After != nil {
		tableMap := data.Payload.After.(map[string]interface{})
		dats := data.Schema.Fields[1].Fields
		// RenameColumn. NewName and oldName are removed from tableMap
		for _, v := range config.RenameColumn {
			tableMap[v.NewName] = tableMap[v.OldName]
			delete(tableMap, v.OldName)
			// Set the old name to the new name
			for i := range dats {
				// Set the field of the column to the new name
				if dats[i].Field == v.OldName {
					dats[i].Field = v.NewName
				}
			}
		}
		data.Payload.After = tableMap
		data.Schema.Fields[1].Fields = dats
	}
	// data. Payload. Before is not nil.
	if data.Payload.Before != nil {
		tableMapBefore := data.Payload.Before.(map[string]interface{})
		dats := data.Schema.Fields[1].Fields
		// RenameColumn. NewName and oldName are removed from tableMapBefore
		for _, v := range config.RenameColumn {
			tableMapBefore[v.NewName] = tableMapBefore[v.OldName]
			delete(tableMapBefore, v.OldName)
			// Set the old name to the new name
			for i := range dats {
				// Set the field of the column to the new name
				if dats[i].Field == v.OldName {
					dats[i].Field = v.NewName
				}
			}
		}
		data.Payload.Before = tableMapBefore
		data.Schema.Fields[1].Fields = dats
	}
	return data
}

// RenameColumnDest renames columns in data schema. The renaming is done in a DDLTransform field.
//
// Args:
//
//	data: The data to update. Should be an auto generated type with schema. Fields [ 1 ] field.
//	config: The configuration for the DDLTransform that was used
func RenameColumnDest(data model.AutoGenerated, config config.DDLTransform) model.AutoGenerated {
	dataSchemaFields := data.Schema.Fields[1].Fields

	// RenameColumn. NewName is the old name of the column
	for _, v := range config.RenameColumn {
		// This function is used to set the old name of the dataSchemaFields
		for i := range dataSchemaFields {
			// This method is used to set the name of the field in the dataSchemaFields array.
			if dataSchemaFields[i].Field == v.NewName {
				dataSchemaFields[i].Field = v.OldName
			}
		}
	}
	data.Schema.Fields[1].Fields = dataSchemaFields
	// This method is used to remove the old names from the payload.
	if data.Payload.After != nil {
		tableMap := data.Payload.After.(map[string]interface{})
		dats := data.Schema.Fields[1].Fields
		// RenameColumn. NewName is the old name of the column.
		for _, v := range config.RenameColumn {
			tableMap[v.OldName] = tableMap[v.NewName]
			delete(tableMap, v.NewName)
			// Set the old name to the old name
			for i := range dats {
				// Set the field to the old name
				if dats[i].Field == v.NewName {
					dats[i].Field = v.OldName
				}
			}

		}
		data.Payload.After = tableMap
		data.Schema.Fields[1].Fields = dats
	}
	// data. Payload. Before is not nil.
	if data.Payload.Before != nil {
		tableMapBefore := data.Payload.Before.(map[string]interface{})
		dats := data.Schema.Fields[1].Fields
		// RenameColumn. NewName is the old name of the column.
		for _, v := range config.RenameColumn {
			tableMapBefore[v.OldName] = tableMapBefore[v.NewName]
			delete(tableMapBefore, v.NewName)
			// Set the old name to the old name
			for i := range dats {
				// Set the field to the old name
				if dats[i].Field == v.NewName {
					dats[i].Field = v.OldName
				}
			}
		}
		data.Payload.Before = tableMapBefore
		data.Schema.Fields[1].Fields = dats
	}
	return data
}

// DebeziumPostgresTemporalMap returns a map of date time and timestamp for use in Postgres
