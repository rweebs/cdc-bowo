func NewCDCDestServices(dbSource lib.Database, dbDest lib.Database, rdb lib.Cache) *CDCDestServices {
	return &CDCDestServices{
		dbSource:        dbSource,
		dbDest:          dbDest,
		rdb:             rdb,
		primaryKeyList:  initPrimaryKeyList(dbSource.Db),
		redisStreamList: initRedisStreamList(dbSource.Db, rdb.Cache, "destRedisStreamList"),
		timeStampCutOff: time.Now().UnixNano() / int64(time.Millisecond),
	}
}
